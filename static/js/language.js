/* =========================================================
   APPLY TRANSLATIONS
   ========================================================= */

function applyTranslations(language) {

    const selectedLanguage =
        translations[language] || translations.en;


    document
        .querySelectorAll("[data-translate]")
        .forEach(element => {

            const key =
                element.dataset.translate;


            if (selectedLanguage[key]) {

                element.textContent =
                    selectedLanguage[key];

            }

        });


    /*
       Translate placeholders
    */

    document
        .querySelectorAll("[data-placeholder]")
        .forEach(element => {

            const key =
                element.dataset.placeholder;


            if (selectedLanguage[key]) {

                element.placeholder =
                    selectedLanguage[key];

            }

        });


    /*
       Save selected language
    */

    localStorage.setItem(
        "mindspaceLanguage",
        language
    );


    document.documentElement.lang =
        language;


    /*
       Let other JavaScript files know
       that the language changed.
    */

    document.dispatchEvent(
        new CustomEvent(
            "mindspaceLanguageChanged",
            {
                detail: {
                    language: language
                }
            }
        )
    );

}


/* =========================================================
   INITIALIZE LANGUAGE
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    () => {

        const selector =
            document.getElementById(
                "languageSelector"
            );


        const savedLanguage =
            localStorage.getItem(
                "mindspaceLanguage"
            ) || "en";


        if (selector) {

            selector.value =
                savedLanguage;


            selector.addEventListener(
                "change",
                () => {

                    applyTranslations(
                        selector.value
                    );

                }
            );

        }


        applyTranslations(
            savedLanguage
        );

    }
);